export const STORAGE_KEY_WHITELIST = 'upm_eppt_whitelist_users';

/**
 * Normalizes email address for consistent lookup
 */
export function normalizeEmail(email: string): string {
  let clean = email.trim().toLowerCase();
  if (clean && !clean.includes('@')) {
    clean = `${clean}@upm.edu.my`;
  }
  return clean;
}

/**
 * Validates a user login against the approved whitelist.
 * Returns the WhitelistUser if authorized, or an error reason.
 */
export function authenticateWhitelistUser(
  emailInput: string,
  passwordInput: string,
  userList: WhitelistUser[] = INITIAL_WHITELIST_USERS
): { success: boolean; user?: WhitelistUser; error?: string } {
  const cleanEmail = normalizeEmail(emailInput);
  const trimmedPassword = passwordInput.trim();

  if (!cleanEmail) {
    return { success: false, error: 'Sila masukkan emel rasmi institusi (@upm.edu.my).' };
  }

  if (!trimmedPassword) {
    return { success: false, error: 'Sila masukkan kata laluan yang ditetapkan.' };
  }

  // Find user in approved whitelist
  const matchedUser = userList.find(
    (u) => u.email.toLowerCase() === cleanEmail || (u.staffId && u.staffId.toLowerCase() === cleanEmail.split('@')[0])
  );

  // Check 1: User existence in whitelist
  if (!matchedUser) {
    return {
      success: false,
      error:
        'Access Denied: Emel ini tidak tersenarai dalam senarai putih pengguna yang diluluskan (Approved Whitelist). Sila hubungi Pentadbir Sistem (System Administrator) untuk kebenaran akses.',
    };
  }

  // Check 2: Account active status (controlled only by System Administrator)
  if (!matchedUser.isActive) {
    return {
      success: false,
      error:
        'Access Denied: Akaun anda telah dinyahaktifkan oleh Pentadbir Sistem. Sila hubungi Unit Perolehan HSAAS untuk bantuan.',
    };
  }

  // Check 3: Assigned password validation
  if (matchedUser.password !== trimmedPassword) {
    return {
      success: false,
      error:
        'Access Denied: Kata laluan yang dimasukkan tidak tepat. Sila pastikan anda menggunakan kata laluan rasmi yang telah ditetapkan oleh Pentadbir Sistem.',
    };
  }

  return { success: true, user: matchedUser };
}
